import json
import time
from enum import Enum
from pathlib import Path

import typer
from rich.console import Console
from rich.panel import Panel
from rich.table import Table

from .analyzer import analyze
from .llm import LLMError
from .parser import parse_file
from .stats import build_stats

app = typer.Typer(help="LogLens — AI-powered log analyzer.", no_args_is_help=True)
console = Console()


class Provider(str, Enum):
    ollama = "ollama"
    api = "api"


def load_entries(path: Path):
    if not path.exists():
        console.print(f"[red]File not found:[/red] {path}")
        raise typer.Exit(code=1)
    return parse_file(path)


def show_stats(stats: dict) -> None:
    table = Table(title="Log statistics")
    table.add_column("Metric", style="cyan")
    table.add_column("Value", justify="right")

    table.add_row("Total lines", f"{stats['total_lines']:,}")
    table.add_row("Skipped lines", str(stats["skipped_lines"]))
    for level, count in stats["levels"].items():
        table.add_row(f"Level: {level}", f"{count:,}")
    for service, count in stats["errors_by_service"].items():
        table.add_row(f"Errors: {service}", str(count))
    table.add_row(
        "Spike hours", ", ".join(f"{h}:00" for h in stats["spike_hours"]) or "none"
    )

    console.print(table)


@app.command()
def stats(path: Path = typer.Argument(..., help="Path to the log file")) -> None:
    """Show log statistics (no LLM)."""
    entries, skipped = load_entries(path)
    show_stats(build_stats(entries, skipped))


@app.command()
def analyze_cmd(
    path: Path = typer.Argument(..., help="Path to the log file"),
    provider: Provider = typer.Option(
        Provider.ollama, "--provider", "-p", help="Which model to use"
    ),
    out: Path | None = typer.Option(
        None, "--out", "-o", help="Save the report as JSON"
    ),
) -> None:
    """Analyze logs and generate an AI incident report."""
    entries, skipped = load_entries(path)

    start = time.perf_counter()
    try:
        with console.status(f"Asking {provider.value}..."):
            stats_data, report = analyze(entries, skipped, provider.value)
    except LLMError as e:
        console.print(f"[red]Error:[/red] {e}")
        raise typer.Exit(code=1)
    elapsed = time.perf_counter() - start

    show_stats(stats_data)

    body = (
        f"[bold]Severity:[/bold] {report.severity.upper()}\n\n"
        f"[bold]Summary:[/bold] {report.summary}\n\n"
        f"[bold]Affected:[/bold] {', '.join(report.affected_services)}\n\n"
        f"[bold]Probable cause:[/bold] {report.probable_cause}\n\n"
        "[bold]Timeline:[/bold]\n"
        + "\n".join(f"  • {t}" for t in report.timeline)
        + "\n\n"
        "[bold]Actions:[/bold]\n"
        + "\n".join(f"  {i}. {a}" for i, a in enumerate(report.recommended_actions, 1))
    )
    color = {"low": "green", "medium": "yellow", "high": "red", "critical": "bold red"}[
        report.severity
    ]
    console.print(Panel(body, title="Incident report", border_style=color))
    console.print(f"[dim]Generated by {provider.value} in {elapsed:.1f}s[/dim]")

    if out:
        out.write_text(json.dumps(report.model_dump(), indent=2), encoding="utf-8")
        console.print(f"[green]Saved to[/green] {out}")


# expose the command as `analyze` (the function name avoids clashing with analyzer.analyze)
app.command(name="analyze")(analyze_cmd)
app.registered_commands = [
    c for c in app.registered_commands if c.name != "analyze-cmd"
]


if __name__ == "__main__":
    app()
